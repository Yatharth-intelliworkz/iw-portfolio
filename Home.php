                function initSplitText() {

                    const TRIGGER_CONFIGS = {
                        default: {
                            desktop: {
                                start: "top bottom",
                                end: "top 70%"
                            },
                            mobile: {
                                start: "top bottom",
                                end: "top 70%"
                            }
                        },
                        early: {
                            desktop: {
                                start: "top bottom",
                                end: "top 99%"
                            },
                            mobile: {
                                start: "top bottom",
                                end: "top 99%"
                            }
                        },
                        late: {
                            desktop: {
                                start: "top bottom",
                                end: "top 40%"
                            },
                            mobile: {
                                start: "top bottom",
                                end: "top 40%"
                            }
                        }
                    };

                    // Animation types
                    const ANIMATION_TYPES = {
                        'lines-slide-up': {
                            splitType: 'lines',
                            animation: (elements, lineWrappers) => ({
                                yPercent: 100,
                                opacity: 0,
                                stagger: 0.05,
                                duration: 1,
                                ease: "expo.out"
                            })
                        }
                    };

                    class TextAnimator {
                        constructor() {
                            this.initialized = false;
                            this.elements = [];
                            this.splitInstances = new Map();
                            this.timelineInstances = new Map();

                            // Add required CSS
                            this.addStyles();

                            // Apply initial CSS
                            document.querySelectorAll('[data-split-text]').forEach(el => {
                                el.style.visibility = 'hidden';
                            });

                            this.init();
                        }

                        addStyles() {
                            const styles = `
        .split-line-wrapper {
          overflow: hidden;
          position: relative;
          display: block;
          padding-bottom: 0.3em;
          margin-top: -0.3em;
        }
        .split-line {
          display: block;
          position: relative;
        }
      `;

                            const styleSheet = document.createElement('style');
                            styleSheet.textContent = styles;
                            document.head.appendChild(styleSheet);
                        }

                        init() {
                            if (this.initialized) return;

                            const elements = Array.from(document.querySelectorAll('[data-split-text]'))
                                .filter(element => element.getAttribute('data-slide-up') !== 'true');

                            if (elements.length === 0) return;

                            // Skip animation if user prefers reduced motion
                            if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
                                elements.forEach(el => {
                                    el.style.visibility = 'visible';
                                    el.style.opacity = '1';
                                });
                                return;
                            }

                            elements.forEach(element => this.setupElement(element));

                            // Make sure elements with data-slide-up="true" are visible
                            document.querySelectorAll('[data-split-text][data-slide-up="true"]')
                                .forEach(el => {
                                    el.style.visibility = 'visible';
                                    el.style.opacity = '1';
                                });

                            this.initialized = true;
                        }

                        wrapLines(split) {
                            const wrappers = [];
                            split.lines.forEach(line => {
                                const wrapper = document.createElement('div');
                                wrapper.className = 'split-line-wrapper';
                                line.parentNode.insertBefore(wrapper, line);
                                wrapper.appendChild(line);
                                wrappers.push(wrapper);
                            });
                            return wrappers;
                        }

                        setupElement(element) {
                            // Double-check data-slide-up attribute before setup
                            if (element.getAttribute('data-slide-up') === 'true') {
                                element.style.visibility = 'visible';
                                element.style.opacity = '1';
                                return;
                            }

                            const animationType = element.getAttribute('data-split-text');
                            const triggerType = element.getAttribute('data-trigger-type') || 'default';

                            if (!ANIMATION_TYPES[animationType]) {
                                console.warn(`Unknown animation type: ${animationType}`);
                                return;
                            }

                            // Store original text for screen readers
                            const originalText = element.textContent;

                            // Setup accessibility attributes
                            element.setAttribute('aria-label', originalText);
                            element.setAttribute('role', 'text');
                            element.style.visibility = 'visible';

                            try {
                                // Create split text instance with accessibility considerations
                                const splitConfig = ANIMATION_TYPES[animationType];
                                const split = new SplitText(element, {
                                    type: splitConfig.splitType,
                                    linesClass: "split-line",
                                    wordsClass: "split-word",
                                    charsClass: "split-char"
                                });

                                // Wrap lines in overflow hidden containers if it's a line animation
                                const lineWrappers = splitConfig.splitType === 'lines' ? this.wrapLines(split) :
                                    null;

                                // Hide split elements from screen readers
                                split.lines.forEach(line => line.setAttribute('aria-hidden', 'true'));
                                split.words.forEach(word => word.setAttribute('aria-hidden', 'true'));
                                split.chars.forEach(char => char.setAttribute('aria-hidden', 'true'));

                                // Store split instance for cleanup
                                this.splitInstances.set(element, split);

                                // Get trigger configuration based on screen size
                                const isMobile = window.innerWidth < 768;
                                const triggerConfig = TRIGGER_CONFIGS[triggerType][isMobile ? 'mobile' : 'desktop'];

                                // Create and configure timeline
                                const tl = gsap.timeline({
                                    scrollTrigger: {
                                        trigger: element,
                                        start: triggerConfig.start,
                                        end: triggerConfig.end,
                                        toggleActions: "none play none reset",
                                        onEnter: () => ScrollTrigger.refresh()
                                    }
                                });

                                // Add animation to timeline
                                const elements = split[splitConfig.splitType];
                                const animationConfig = splitConfig.animation(elements, lineWrappers);
                                tl.from(elements, animationConfig);

                                // Store timeline instance for cleanup
                                this.timelineInstances.set(element, tl);

                                // Add element to tracked elements
                                this.elements.push(element);

                            } catch (error) {
                                console.error('Error setting up animation:', error);
                                // If animation fails, ensure content is visible
                                element.style.visibility = 'visible';
                                element.style.opacity = '1';
                            }
                        }

                        // Handle window resize
                        handleResize() {
                            ScrollTrigger.refresh();
                        }

                        // Clean up all instances
                        destroy() {
                            this.splitInstances.forEach((split, element) => {
                                // Remove line wrappers if they exist
                                split.lines.forEach(line => {
                                    const wrapper = line.parentElement;
                                    if (wrapper?.classList.contains('split-line-wrapper')) {
                                        wrapper.parentNode.insertBefore(line, wrapper);
                                        wrapper.remove();
                                    }
                                });

                                // Remove aria attributes before reverting
                                split.lines.forEach(line => line.removeAttribute('aria-hidden'));
                                split.words.forEach(word => word.removeAttribute('aria-hidden'));
                                split.chars.forEach(char => char.removeAttribute('aria-hidden'));
                                split.revert();
                            });
                            this.splitInstances.clear();

                            this.timelineInstances.forEach(tl => tl.kill());
                            this.timelineInstances.clear();

                            // Reset visibility and remove accessibility attributes
                            document.querySelectorAll('[data-split-text]').forEach(el => {
                                el.style.visibility = 'visible';
                                el.removeAttribute('aria-hidden');
                                el.removeAttribute('aria-label');
                                el.removeAttribute('role');
                            });

                            this.elements = [];
                            this.initialized = false;
                        }
                    }

                    // Create instance
                    const textAnimator = new TextAnimator();
                }

                // Equivalent to $(document).ready(...)
                document.addEventListener('DOMContentLoaded', function() {
                    initSplitText();
                });
                </script>
