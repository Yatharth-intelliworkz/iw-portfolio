                    function initProjectFilter() {

                        const $filterButtons = $('.filter_item');
                        const $projectItems = $('.project_item');
                        const $allFilter = $('.filter_item.all');
                        let activeFilter = null;

                        const normalizeText = text => text.toLowerCase().trim();

                        const showAllProjects = () => {
                            $projectItems.css({
                                'opacity': '1',
                                'pointerEvents': 'auto'
                            });
                        };

                        const updateActiveStates = ($activeButton) => {
                            $filterButtons.removeClass('is-active');
                            if ($activeButton) {
                                $activeButton.addClass('is-active');
                            }

                            if ($activeButton && !$activeButton.hasClass('all')) {
                                $filterButtons.not($activeButton).css('opacity', '0.2');
                                $activeButton.css('opacity', '1');
                            } else {
                                $filterButtons.css('opacity', '1');
                            }
                        };

                        const applyFilter = (filterValue, toggle = false) => {
                            const normalizedFilter = normalizeText(filterValue);

                            if (toggle && normalizedFilter === activeFilter) {
                                activeFilter = null;
                                updateActiveStates($allFilter);
                                showAllProjects();
                                history.pushState({}, '', window.location.pathname);
                                return;
                            }

                            const $matchingButton = $filterButtons.filter(function() {
                                return normalizeText($(this).text()) === normalizedFilter;
                            });

                            if ($matchingButton.length) {
                                updateActiveStates($matchingButton);
                                activeFilter = normalizedFilter;

                                $projectItems.each(function() {
                                    const $project = $(this);
                                    const $disciplineDiv = $project.find('.project_disciplines');
                                    const disciplines = $disciplineDiv.find('.discipline')
                                        .map(function() {
                                            return normalizeText($(this).text());
                                        })
                                        .get();

                                    if (disciplines.includes(normalizedFilter)) {
                                        $project.css({
                                            'opacity': '1',
                                            'pointerEvents': 'auto'
                                        });
                                    } else {
                                        $project.css({
                                            'opacity': '0.2',
                                            'pointerEvents': 'none'
                                        });
                                    }
                                });
                            }
                        };

                        const checkURLFilter = () => {
                            const urlParams = new URLSearchParams(window.location.search);
                            const filterParam = urlParams.get('filter');
                            if (filterParam) {
                                applyFilter(filterParam);
                            }
                        };

                        $filterButtons.on({
                            mouseenter: function() {
                                const $this = $(this);
                                const $activeButton = $filterButtons.filter('.is-active');

                                if ($activeButton.hasClass('all')) {
                                    $filterButtons.not($this).css('opacity', '0.2');
                                    $this.css('opacity', '1');
                                } else if (!$this.hasClass('is-active')) {
                                    $this.css('opacity', '1');
                                }
                            },
                            mouseleave: function() {
                                const $activeButton = $filterButtons.filter('.is-active');

                                if ($activeButton.hasClass('all')) {
                                    $filterButtons.css('opacity', '1');
                                } else {
                                    $activeButton.css('opacity', '1');
                                    $filterButtons.not($activeButton).css('opacity', '0.2');
                                }
                            }
                        });

                        $allFilter.on('click', function() {
                            activeFilter = null;
                            updateActiveStates($(this));
                            showAllProjects();
                            history.pushState({}, '', window.location.pathname);
                        });

                        $filterButtons.not('.all').on('click', function() {
                            const $this = $(this);
                            const discipline = normalizeText($this.text());
                            applyFilter(discipline, true);

                            if (activeFilter) {
                                const newUrl =
                                    `${window.location.pathname}?filter=${encodeURIComponent(discipline)}`;
                                history.pushState({}, '', newUrl);
                            }
                        });

                        $(document).ready(function() {
                            const urlParams = new URLSearchParams(window.location.search);
                            const filterParam = urlParams.get('filter');

                            if (filterParam) {
                                checkURLFilter();
                            } else {
                                $allFilter.addClass('is-active');
                                $filterButtons.css('opacity', '1');
                                showAllProjects();
                            }
                        });
                    }

                    // Equivalent to $(document).ready(...)
                    document.addEventListener('DOMContentLoaded', function() {
                        initProjectFilter();
                    });
